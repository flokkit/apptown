type exchange struct {
	method, path, query string
	body                []byte
}

// codeAppTown answers like an AppTown that starts projects from code, recording
// every request with its raw body.
func codeAppTown(t *testing.T, bundle []byte) *[]exchange {
	t.Helper()
	var mu sync.Mutex
	seen := &[]exchange{}
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		raw, _ := io.ReadAll(r.Body)
		path := strings.TrimPrefix(r.URL.Path, "/api/v1")
		mu.Lock()
		*seen = append(*seen, exchange{r.Method, path, r.URL.RawQuery, raw})
		mu.Unlock()
		switch {
		case r.Method == "POST" && path == "/projects":
			_, _ = io.WriteString(w, `{"slug":"moved","name":"moved"}`)
		case strings.HasPrefix(path, "/projects/moved/repo/from-"):
			_, _ = io.WriteString(w, `{"slug":"moved","defaultBranch":"main"}`)
		case path == "/projects/moved/secrets":
			_, _ = io.WriteString(w, `{"declared":true,"secrets":[{"name":"STRIPE_KEY"},{"name":"SESSION_SECRET","generate":true}]}`)
		case path == "/projects/moved/repo/bundle":
			_, _ = w.Write(bundle)
		default:
			w.WriteHeader(404)
			_, _ = io.WriteString(w, `{"error":"no"}`)
		}
	}))
	t.Cleanup(srv.Close)
	prev := api
	api = &client{base: srv.URL, actor: "tester", http: srv.Client(), wait: func(time.Duration) {},
		getenv: func(k string) string { return map[string]string{"APPTOWN_TOKEN": "apptown_tok"}[k] }}
	t.Cleanup(func() { api = prev })
	return seen
}

// `apptown new --from <bundle>` creates the project, uploads the file's exact
// bytes to the bundle door (never the empty-repository door), and names
// the secrets the code declares. A bad --from is refused before any
// project is made.
//
// Kills: the bundle read but not sent whole; the empty /repo initialized
// as well; --secret-for-git accepted with a bundle; a missing file found
// only after the project exists.
func TestNewFromABundleUploadsItAndNamesTheSecrets(t *testing.T) {
	seen := codeAppTown(t, nil)
	file := filepath.Join(t.TempDir(), "p.bundle")
	content := []byte("# v2 git bundle\nnot really, but bytes are bytes\x00\x01")
	if err := os.WriteFile(file, content, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := run(t, "new", "moved", "--from", file)
	if err != nil {
		t.Fatal(err)
	}
	// The fourth request reads whether a model is set up, for the hint.
	if len(*seen) != 4 || (*seen)[0].path != "/projects" || (*seen)[1].path != "/projects/moved/repo/from-bundle" || !bytes.Equal((*seen)[1].body, content) || (*seen)[3].path != "/setup" {
		t.Fatalf("requests: %+v", *seen)
	}
	if !strings.Contains(out, "STRIPE_KEY") || !strings.Contains(out, "generated by AppTown on first deploy: SESSION_SECRET") {
		t.Fatalf("the declared secrets are not named: %s", out)
	}
	*seen = nil
	for _, args := range [][]string{
		{"new", "moved", "--from", filepath.Join(t.TempDir(), "missing.bundle")},
		{"new", "moved", "--from", file, "--secret-for-git", "GITLAB_TOKEN"},
	} {
		if _, err := run(t, args...); err == nil {
			t.Fatalf("%v was accepted", args)
		}
	}
	if len(*seen) != 0 {
		t.Fatalf("a refused --from made requests: %+v", *seen)
	}
}

// `apptown new --from <https-url>` sends the URL and the secret's name, never
// a value; AppTown fetches.
func TestNewFromAURLNamesTheSecretOnly(t *testing.T) {
	seen := codeAppTown(t, nil)
	if _, err := run(t, "new", "moved", "--from", "https://gitlab.example/team/app.git", "--secret-for-git", "GITLAB_TOKEN", "--branch", "trunk"); err != nil {
		t.Fatal(err)
	}
	r := (*seen)[1]
	if r.path != "/projects/moved/repo/from-url" || !strings.Contains(string(r.body), `"credentialSecret":"GITLAB_TOKEN"`) || !strings.Contains(string(r.body), `"branch":"trunk"`) {
		t.Fatalf("request: %s %s", r.path, r.body)
	}
}

// `apptown bundle -p` writes the download's exact bytes to standard output.
func TestBundleWritesTheDownload(t *testing.T) {
	want := []byte("bundle bytes\x00\xff")
	codeAppTown(t, want)
	out, err := run(t, "bundle", "-p", "moved")
	if err != nil || out != string(want) {
		t.Fatalf("bundle = %q %v", out, err)
	}
}

// An import whose answer was lost (a 502 after it was sent, or the
// connection broken before an answer) may have started the repository: the
// error never says the repository is absent and never advises deleting the
// project. AppTown's own refusal still does.
func TestAnImportWithAnUnknownOutcomeAdvisesNoDeletion(t *testing.T) {
	file := filepath.Join(t.TempDir(), "p.bundle")
	if err := os.WriteFile(file, []byte("bytes"), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, from := range []string{file, "https://gitlab.example/team/app.git"} {
		for name, answer := range map[string]func(w http.ResponseWriter){
			"gateway": func(w http.ResponseWriter) { w.WriteHeader(502) },
			"lost":    func(w http.ResponseWriter) { panic(http.ErrAbortHandler) }, // the connection closes, no answer
			"refusal": func(w http.ResponseWriter) {
				w.WriteHeader(422)
				_, _ = io.WriteString(w, `{"error":"import refused"}`)
			},
		} {
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				_, _ = io.ReadAll(r.Body)
				if strings.Contains(r.URL.Path, "/repo/from-") {
					answer(w)
					return
				}
				_, _ = io.WriteString(w, `{"slug":"moved","name":"moved"}`)
			}))
			prev := api
			api = &client{base: srv.URL, actor: "tester", http: srv.Client(), wait: func(time.Duration) {}, getenv: func(string) string { return "" }}
			_, err := run(t, "new", "moved", "--from", from)
			api = prev
			srv.Close()
			advisesDeletion := err != nil && (strings.Contains(err.Error(), "without a repository") || strings.Contains(err.Error(), "apptown delete"))
			if err == nil || advisesDeletion != (name == "refusal") || (name != "refusal" && !strings.Contains(err.Error(), "check before deleting anything")) {
				t.Fatalf("--from %s, %s: %v", from, name, err)
			}
		}
	}
}
