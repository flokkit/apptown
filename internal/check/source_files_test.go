func sourceRubric() check.Declared {
	return check.Declared{Declaration: check.Declaration{Name: "source", Expects: "judge source", AppliesTo: []string{"part"}, Evaluator: "llm", Scope: "tree", Rubric: "judge", SourceFiles: true}}
}

// Programming language data, rather than a short extension list or tools, selects
// all source in the applicable folder, including tests and mixed-language UI.
func TestSourceFilesCollectsProgrammingLanguages(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name  string
		files map[string]string
	}{
		{"Java", map[string]string{"src/Main.java": "public class Main { public static void main(String[] args) {} }"}},
		{"PHP", map[string]string{"index.php": "<?php echo 'Hello'; ?>"}},
		{"React", map[string]string{"src/App.tsx": "export const App = () => <main>Hello</main>;", "src/view.jsx": "export default () => <div>Hello</div>;"}},
		{"mixed", map[string]string{"main.go": "package main\nfunc main() {}", "ui/App.tsx": "export const App = () => <main>Hello</main>;", "main_test.go": "package main\nimport \"testing\"\nfunc TestMain(t *testing.T) {}"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			var want []string
			for rel, body := range tc.files {
				writeFile(t, dir, "app/"+rel, body)
				want = append(want, "app/"+rel)
			}
			slices.Sort(want)
			src := check.Source{Tree: dir, Parts: []check.Part{{Name: "app", Folder: "app", Tools: []string{"go"}}}}
			it := check.TreeItems([]check.Declared{sourceRubric()}, src)[0]
			if it.Unreadable != "" || !slices.Equal(it.Files, want) || it.MatchingFiles != len(want) {
				t.Fatalf("source evidence: %+v; want %v", it, want)
			}
		})
	}
}

// A tree judgement unions applicable folders once. Explicit context remains
// repository-relative and survives source-only exclusions.
func TestSourceFilesRespectsPartBoundariesAndExplicitContext(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for _, rel := range []string{"api/main.go", "api/ui/App.tsx", "api2/other.go", "other/main.go", "api/scratch/test.go", "api/Documentation/example.go", "api/vendor/v.go", "api/node_modules/v.js", "api/generated.go", "api/late-generated.go", "api/binary.go", "api/readme.md", "api/config.yaml", "api/index.html", "api/style.css"} {
		body := "package main\nfunc main() {}"
		switch rel {
		case "api/late-generated.go":
			body = "//" + strings.Repeat("x", 13*1024) + "\n// Code generated by test. DO NOT EDIT.\npackage main"
		case "api/generated.go":
			body = "// Code generated by test. DO NOT EDIT.\npackage main"
		case "api/binary.go":
			body = "binary\x00"
		case "api/ui/App.tsx":
			body = "export const App = () => <main>Hello</main>;"
		case "api/readme.md":
			body = "# Explicit context"
		}
		writeFile(t, dir, rel, body)
	}
	writeFile(t, dir, ".apptown/app.yaml", "app: context")
	outside := t.TempDir()
	writeFile(t, outside, "outside.go", "package outside")
	if err := os.Symlink(outside, filepath.Join(dir, "api", "link")); err != nil {
		t.Fatal(err)
	}
	c := sourceRubric()
	c.AppliesTo = []string{"tool:go"}
	c.Files = []string{".apptown/app.yaml", "api/readme.md", "api/main.go"}
	src := check.Source{Tree: dir, Parts: []check.Part{{Name: "a", Folder: "api", Tools: []string{"go"}}, {Name: "b", Folder: "api", Tools: []string{"go"}}, {Name: "ui", Folder: "api/ui", Tools: []string{"go"}}, {Name: "other", Folder: "other", Tools: []string{"java"}}}, NotAppCode: []string{"api/scratch"}}
	it := check.TreeItems([]check.Declared{c}, src)[0]
	want := []string{".apptown/app.yaml", "api/main.go", "api/readme.md", "api/ui/App.tsx"}
	if it.Unreadable != "" || !slices.Equal(it.Files, want) || it.MatchingFiles != len(want) {
		t.Fatalf("evidence: %+v; want %v", it, want)
	}
	// The caller may stage the checked tree behind a link; internal links stay excluded.
	link := filepath.Join(t.TempDir(), "tree")
	if err := os.Symlink(dir, link); err != nil {
		t.Fatal(err)
	}
	src.Tree = link
	linked := check.TreeItems([]check.Declared{c}, src)[0]
	if linked.Hash != it.Hash {
		t.Fatalf("root link changed evidence: %+v", linked)
	}
}

func TestSourceFilesReportsUnknownAndRequiresContext(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeFile(t, dir, "app/rules.unknown-format", "unclassified application rules")
	c := sourceRubric()
	src := check.Source{Tree: dir, Parts: []check.Part{{Name: "app", Folder: "app"}}}
	it := check.TreeItems([]check.Declared{c}, src)[0]
	if !strings.Contains(it.Evidence, "unclassified: app/rules.unknown-format") || !strings.Contains(it.Evidence, "do not establish absence of code") || it.MatchingFiles != 0 {
		t.Fatalf("unknown evidence: %+v", it)
	}
	for _, bad := range []check.Source{{Tree: dir, NoContract: true}, {Tree: dir, PartsErr: errors.New("unreadable contract")}, {Tree: dir}} {
		for _, words := range [][]string{{"part"}, {"repository"}} {
			c.AppliesTo = words
			it := check.TreeItems([]check.Declared{c}, bad)[0]
			if it.Unreadable == "" {
				t.Fatalf("missing context accepted: %+v", bad)
			}
			j := check.Judge{Complete: check.CompleterFunc(func(context.Context, string, string) (check.Completion, error) {
				t.Fatal("missing context sent to model")
				return check.Completion{}, nil
			})}
			evs, err := j.Evaluate(t.Context(), []check.Declared{c}, bad, check.Gate)
			if err != nil || len(evs) != 1 || evs[0].Outcome != check.CannotAssess {
				t.Fatalf("missing context: %+v, %v", evs, err)
			}
		}
	}
}

func TestSourceFilesSelectorValidationAndIdentity(t *testing.T) {
	t.Parallel()
	c := sourceRubric().Declaration
	if err := check.Validate([]check.Declaration{c}); err != nil {
		t.Fatal(err)
	}
	base := check.LLMEvaluatorVersion(c)
	c.SourceFiles = false
	if base == check.LLMEvaluatorVersion(c) || !strings.Contains(base, "pack-v4") {
		t.Fatalf("source selection must change evaluator identity: %s", base)
	}
	for _, scope := range []string{"diff", ""} {
		c := sourceRubric().Declaration
		c.Scope = scope
		if err := check.Validate([]check.Declaration{c}); err == nil {
			t.Fatalf("sourceFiles accepted for scope %q", scope)
		}
	}
}

func TestSourceFilesBudgetsCountEligibleSource(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for _, name := range []string{"a.java", "b.java", "c.java", "d.java", "e.java", "f.java"} {
		writeFile(t, dir, name, "class App {}\n"+strings.Repeat(" ", 20*1024))
	}
	writeFile(t, dir, "vendor/vendor.java", "class Vendor {}")
	c := sourceRubric()
	src := check.Source{Tree: dir, Parts: []check.Part{{Name: "app", Folder: "."}}}
	checks := []check.Declared{c, c, c, c, c, c}
	items := check.TreeItems(checks, src)
	total := 0
	for i, it := range items {
		total += len(it.Evidence)
		if it.Unreadable != "" || it.MatchingFiles != 6 || len(it.Evidence) > 48*1024 {
			t.Fatalf("budget counts: %+v", it)
		}
		if i == 0 && (len(it.Files) != 3 || !strings.Contains(it.Evidence, "3 more matching file(s) omitted")) {
			t.Fatalf("rubric budget: %+v", it)
		}
		if i == 5 && (len(it.Files) != 0 || !strings.Contains(it.Evidence, "project bundle cap")) {
			t.Fatalf("batch budget: %+v", it)
		}
	}
	if total > 160*1024 {
		t.Fatalf("batch size %d", total)
	}
}
