//go:build integration

package gitexec

import (
	"context"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"sync"
	"testing"
)

var updateBranchNames = flag.Bool("update-branch-names", false, "rewrite branchname_verdicts_test.go from the installed git's answers")

// gitAcceptsBranchName asks git itself, outside any repository so that it
// expands nothing. Git failing to answer is an error, never a refusal.
func gitAcceptsBranchName(dir, name string) (bool, error) {
	out, err := RunEnv(context.Background(), dir, []string{"GIT_CEILING_DIRECTORIES=" + filepath.Dir(dir)}, "check-ref-format", "--branch", name)
	if err == nil {
		return true, nil
	}
	if exit, ok := err.(*exec.ExitError); ok && exit.ExitCode() == 128 && strings.Contains(out, "not a valid branch name") {
		return false, nil
	}
	return false, fmt.Errorf("git check-ref-format --branch %q did not answer: %v: %s", name, err, out)
}

// The recorded table must still be what the installed git answers, and
// CheckBranchName must agree with git directly. git check-ref-format judges
// one name per start, so this costs one git start per name (about 2,600);
// it runs in the integration tier, the unit tier reads the table.
func TestIntegrationCheckBranchNameAgreesWithGit(t *testing.T) {
	dir := t.TempDir()
	names := branchNameTestNames()
	verdicts := make([]branchNameVerdict, len(names))
	errs := make([]error, len(names))
	var wg sync.WaitGroup
	next := make(chan int)
	// Four at a time: git costs a few milliseconds a start, and this test
	// shares the machine with the rest of the tier.
	for w := 0; w < 4; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range next {
				git, err := gitAcceptsBranchName(dir, names[i])
				verdicts[i], errs[i] = branchNameVerdict{names[i], git}, err
			}
		}()
	}
	for i := range names {
		next <- i
	}
	close(next)
	wg.Wait()
	for _, err := range errs {
		if err != nil {
			t.Fatal(err)
		}
	}
	if *updateBranchNames {
		writeBranchNameVerdicts(t, verdicts)
	}
	for i, v := range verdicts {
		if !agreesWithGit(v.name, v.git) {
			t.Errorf("%q: git accepts=%v, CheckBranchName accepts=%v", v.name, v.git, !v.git)
		}
		if *updateBranchNames {
			continue
		}
		if i >= len(gitBranchNameVerdicts) || gitBranchNameVerdicts[i] != v {
			t.Errorf("%q: the recorded table does not hold git's answer (%v); regenerate it (see branchname_verdicts_test.go)", v.name, v.git)
		}
	}
}

func writeBranchNameVerdicts(t *testing.T, verdicts []branchNameVerdict) {
	t.Helper()
	version, err := Run(context.Background(), t.TempDir(), "--version")
	if err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by TestIntegrationCheckBranchNameAgreesWithGit from %s; DO NOT EDIT.
//
// git check-ref-format --branch's answer for each of branchNameTestNames,
// in order. Regenerate after changing the names or upgrading git:
//
//	go test -tags=integration ./internal/gitexec -run '^TestIntegrationCheckBranchNameAgreesWithGit$' -update-branch-names

package gitexec

type branchNameVerdict struct {
	name string
	git  bool
}

var gitBranchNameVerdicts = []branchNameVerdict{
`, version)
	for _, v := range verdicts {
		fmt.Fprintf(&b, "\t{%q, %v},\n", v.name, v.git)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("branchname_verdicts_test.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	// This binary holds the old table, so this run compares only against
	// git; the next run reads the new table.
	t.Log("wrote branchname_verdicts_test.go")
}
