//go:embed integer-identity-baseline.txt
var integerIdentityBaseline string

var createTable = regexp.MustCompile(`^\s*CREATE TABLE (?:IF NOT EXISTS )?([a-z_0-9]+)`)

// integerIdentities is every table.column the schema declares as a
// generated integer key, an identity or a serial, sorted.
func integerIdentities(schema string) []string {
	var out []string
	table := ""
	for _, line := range strings.Split(schema, "\n") {
		if m := createTable.FindStringSubmatch(line); m != nil {
			table = m[1]
			continue
		}
		if table != "" && generatedInteger(line) {
			out = append(out, table+"."+strings.Fields(line)[0])
		}
	}
	slices.Sort(out)
	return out
}

// generatedInteger: a column line whose integer value the database
// generates: GENERATED ... AS IDENTITY, or a SERIAL type.
func generatedInteger(line string) bool {
	if strings.Contains(line, "AS IDENTITY") {
		return true
	}
	f := strings.Fields(strings.ToUpper(line))
	return len(f) > 1 && slices.Contains([]string{"SERIAL", "BIGSERIAL", "SMALLSERIAL", "SERIAL4", "SERIAL8", "SERIAL2"}, strings.TrimSuffix(f[1], ","))
}

