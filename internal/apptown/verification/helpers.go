func writeOSVGoOverride(scanSrc, version string) bool {
	cfgPath := filepath.Join(scanSrc, "osv-scanner.toml")
	if b, err := os.ReadFile(cfgPath); err == nil && strings.Contains(string(b), "GoVersionOverride") {
		return false // the repo made its own call
	}
	f, err := os.OpenFile(cfgPath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return false
	}
	defer f.Close()
	fmt.Fprintf(f, "\n# Generated by AppTown at scan time (never committed): Go stdlib\n"+
		"# advisories are judged against the toolchain that actually builds\n"+
		"# this tree, not go.mod's floor.\nGoVersionOverride = %q\n", version)
	return true
}
func projectOrEmpty(ctx context.Context, db database.Queryer, id ids.ID) project.Project {
	r, err := project.ByIDIn(ctx, db, id)
	if _, err := database.Lookup(err); err != nil {
		log.Printf("read failed: %v", err)
	}
	return r
}
