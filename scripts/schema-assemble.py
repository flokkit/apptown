#!/usr/bin/env python3
"""Assemble current schema fragments as data; numbered migrations stay in Go.

The manifest is ordered explicitly. This tool concatenates the files into the
bundle every sqlc query block reads (sqlc.yaml names it); PostgreSQL/sqlc
validate SQL and its dependency ordering.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = Path('internal/apptown/dbschema/fragments.json')
BUNDLE = Path('internal/apptown/dbschema/schema.sql')


def fragments(root=ROOT):
    paths = json.loads((root / MANIFEST).read_text())
    if not isinstance(paths, list) or not paths or not all(isinstance(p, str) for p in paths):
        raise ValueError('schema manifest must be a nonempty ordered list of paths')
    if len(paths) != len(set(paths)):
        raise ValueError('duplicate schema fragment')
    expected = {str(p.relative_to(root)) for p in (root / 'internal/apptown').rglob('schema.sql') if p != root / BUNDLE}
    expected.add('internal/apptown/dbschema/version.sql')
    if set(paths) != expected:
        raise ValueError(f'schema fragments differ: unlisted {expected - set(paths)}, missing/invalid {set(paths) - expected}')
    for path in paths:
        if not (root / path).is_file():
            raise ValueError(f'missing schema fragment: {path}')
    return paths



def table_owners(root=ROOT):
    """The declaring fragment is the owner; canonical DDL uses public table names."""
    owners = {}
    declaration = re.compile(r'^CREATE TABLE (?:IF NOT EXISTS )?([a-z_][a-z_0-9]*)\s*\(', re.M)
    for path in fragments(root):
        text = (root / path).read_text()
        names = declaration.findall(text)
        statements = re.findall(r'^\s*CREATE\s+TABLE\b', text, re.M | re.I)
        if not names or len(names) != len(statements):
            raise ValueError(f'{path}: use canonical unquoted public CREATE TABLE declarations')
        owner = path.split('/')[2]
        for name in names:
            if name in owners:
                raise ValueError(f'table {name} declared by both {owners[name]} and {owner}')
            owners[name] = owner
    return owners

def query_files(root=ROOT):
    """Every file sqlc reads named queries from: each sqlc.yaml `queries:` entry,
    a file or a directory of .sql files. Gates follow this, not a filename."""
    out = []
    for entry in re.findall(r'^    queries: ([^\n]+)', (root / 'sqlc.yaml').read_text(), re.M):
        path = root / entry.strip()
        if path.is_dir():
            files = sorted(path.glob('*.sql'))
            if not files:
                raise ValueError(f'sqlc query directory has no .sql files: {entry}')
            out.extend(files)
        elif path.is_file():
            out.append(path)
        else:
            raise ValueError(f'sqlc query input is missing: {entry}')
    return out


def assemble(root, paths):
    return '-- Code generated by scripts/schema-assemble.py. DO NOT EDIT.\n\n' + ''.join(
        f'-- Source: {p}\n' + (root / p).read_text().rstrip() + '\n\n' for p in paths)


def outputs(root=ROOT):
    paths = fragments(root)
    table_owners(root)
    return {BUNDLE: assemble(root, paths)}


def run(root=ROOT, check=False):
    stale = []
    for path, text in outputs(root).items():
        if check:
            if not (root / path).is_file() or (root / path).read_text() != text:
                stale.append(str(path))
        else:
            (root / path).write_text(text)
    if stale:
        raise ValueError('generated schema is stale: ' + ', '.join(stale))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        run(check=args.check)
    except (ValueError, OSError) as error:
        parser.exit(1, f'schema assembly: {error}\n')
    print('schema assembly: ok')


if __name__ == '__main__':
    main()
