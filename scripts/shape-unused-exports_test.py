#!/usr/bin/env python3
"""Typed exports count references to objects, including function values."""
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent.parent

class ExportBoundaries(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.directory = Path(cls.temp.name)
        cls.exports = cls.directory / 'exports'
        cls.support = cls.directory / 'support'
        for source, target in [('shape-unused-exports.go', cls.exports), ('shape-test-support.go', cls.support)]:
            subprocess.run(['go', 'build', '-o', str(target), str(ROOT / 'scripts' / source)], cwd=ROOT, check=True)

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def fixture(self, files):
        directory = tempfile.TemporaryDirectory(dir=self.directory)
        self.addCleanup(directory.cleanup)
        root = Path(directory.name)
        files = {'go.mod': 'module github.com/flokkit/apptown\n\ngo 1.27.3\n', **files}
        for name, source in files.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)
        return root

    def test_production_use_requires_another_package_and_ignores_test_helpers(self):
        root = self.fixture({
            'internal/owner/owner.go': '''package owner
func Used() {}
func Own() {}
func TestOnly() {}
func HelperOnly() {}
func TaggedOnly() {}
func Value() {}
func Call() { Own() }
var Callback = Value
type Record struct { Value string `json:"value"` }
type Service struct { private int; Field int }
type Reflected struct { private int; Visible int }
func (s Service) Error() string { return "" }
func (s Service) Unwrap() string { return "" }
var _ error = Service{}
''',
            'internal/owner/owner_test.go': 'package owner_test\nimport ("reflect"; "github.com/flokkit/apptown/internal/owner")\nfunc example() { owner.TestOnly(); reflect.ValueOf(owner.Reflected{}) }\n',
            'internal/owner/ownertest/helper.go': 'package ownertest\nimport "github.com/flokkit/apptown/internal/owner"\nfunc Helper() { owner.HelperOnly() }\n',
            'internal/consumer/consumer.go': 'package consumer\n',
            'internal/consumer/consumer_integration_test.go': '//go:build integration\n\npackage consumer\nimport \"github.com/flokkit/apptown/internal/owner\"\nfunc example(){owner.TaggedOnly()}\n',
            'cmd/app/main.go': 'package main\nimport "github.com/flokkit/apptown/internal/owner"\nfunc main() { owner.Used() }\n',
        })
        rows = json.loads(subprocess.check_output([self.exports, "./..."], cwd=root))
        rows = {row['Name']: row for row in rows if row['Package'].endswith('/owner')}
        self.assertTrue(rows['Used']['Production'])
        for name in ['Own', 'TestOnly', 'HelperOnly', 'Value']:
            self.assertFalse(rows[name]['Production'], name)
        self.assertEqual(rows['TaggedOnly']['Category'], 'review')
        self.assertEqual(rows['Value']['Reason'], 'function used as a value')
        self.assertEqual(rows['Service.Error']['Category'], 'excluded')
        self.assertEqual(rows['Service.Unwrap']['Category'], 'a')
        self.assertEqual(rows['Record.Value']['Category'], 'excluded')
        self.assertEqual(rows['Record']['Category'], 'excluded')
        self.assertEqual(rows['Service.Field']['Category'], 'a')
        self.assertEqual(rows['Reflected']['Category'], 'excluded')
        self.assertEqual(rows['Reflected.Visible']['Category'], 'excluded')
        production = json.loads(subprocess.check_output([self.exports, '-production', './...'], cwd=root))
        self.assertTrue(next(r for r in production if r['Name'] == 'Used')['Production'])
        self.assertFalse(next(r for r in production if r['Name'] == 'TestOnly')['Production'])

    def test_contract_additions_do_not_raise_the_ratchet(self):
        spec = importlib.util.spec_from_file_location('shape', ROOT / 'scripts/shape-check.py')
        shape = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(shape)
        root = self.fixture({'internal/owner/owner.go': 'package owner\nfunc Debt() {}\n', 'internal/deploy/deploy.go': 'package deploy\ntype Driver interface { Deploy() }\n'})
        before = shape.unused_exports(root, self.exports)
        additions = {
            'JSON field': ('internal/view/view.go', 'package view\ntype View struct { Added string `json:"added"` }\n'),
            'deploy driver': ('internal/deploy/driver.go', 'package deploy\ntype local struct{}\nfunc (local) Deploy() {}\nvar active Driver = local{}\n'),
            'DB column': ('internal/record/record.go', '// Code generated by sqlc. DO NOT EDIT.\npackage record\ntype Row struct { Added string }\n'),
            'fake helper': ('internal/owner/ownerfake/fake.go', 'package ownerfake\nfunc Added() {}\n'),
        }
        for name, (file, source) in additions.items():
            with self.subTest(name=name):
                path = root / file
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(source)
                self.assertEqual(shape.unused_exports(root, self.exports), before)
                path.unlink()

    def test_failure_lists_only_new_names_even_when_source_lines_move(self):
        spec = importlib.util.spec_from_file_location('shape', ROOT / 'scripts/shape-check.py')
        shape = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(shape)
        old = 'internal/owner/owner.go:1: Debt (func)'
        new = 'internal/owner/owner.go:9: Added (func)'
        found = ['internal/owner/owner.go:8: Debt (func)', new]
        self.assertEqual(shape.new_unused_exports(found, [shape.export_key(old)]), [new])

    def test_tightening_cannot_raise_the_unused_export_allowance(self):
        spec = importlib.util.spec_from_file_location('shape', ROOT / 'scripts/shape-check.py')
        shape = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(shape)
        self.assertEqual(shape.tightened_counts({'unusedexports': ['a']}, {'unusedexports': 0}),
                         {'unusedexports': 0})
        self.assertEqual(shape.tightened_counts({'unusedexports': ['a']}, {'unusedexports': 3}),
                         {'unusedexports': 1})

    def test_support_imports_allow_support_composition_but_check_all_production_tags(self):
        root = self.fixture({
            'internal/owner/use.go': '''//go:build imaginary
package owner
import alias "github.com/flokkit/apptown/internal/owner/ownerfake"
''',
            'tools/use.go': 'package tools\nimport \"github.com/flokkit/apptown/internal/owner/ownerfake\"\n',
            'internal/owner/use_test.go': 'package owner\nimport "github.com/flokkit/apptown/internal/owner/ownerfake"\n',
            'internal/owner/ownertest/use.go': 'package ownertest\nimport "github.com/flokkit/apptown/internal/owner/ownerfake"\n',
            'internal/owner/comment.go': 'package owner\n// import "github.com/flokkit/apptown/internal/owner/ownerfake"\n',
        })
        found = json.loads(subprocess.check_output([self.support, root]))
        self.assertEqual(len(found), 2, found)
        self.assertFalse(any('ownertest/use.go' in row for row in found))

if __name__ == '__main__':
    unittest.main()
